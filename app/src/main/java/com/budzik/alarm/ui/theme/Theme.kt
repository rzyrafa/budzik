@Composable
fun BudzikTheme(
    darkTheme: Boolean = false, // Enforce warm cream #F5F4EF + contrast black theme
    dynamicColor: Boolean = false, // Enforce curated matte pastel & high-contrast palette
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}

/**
 * Spring physics touch response for buttons, cards, pills and toggles
 * active scale down to 0.94 with natural spring recovery:
 * transition: transform 0.2s cubic-bezier(0.34, 1.56, 0.64, 1)
 * :active { transform: scale(0.94); }
 */
@Composable
fun Modifier.bouncyPress(
    scaleTarget: Float = 0.94f,
    interactionSource: MutableInteractionSource? = null
): Modifier {
    var isPointerPressed by remember { mutableStateOf(false) }
    val isInteractionPressed = interactionSource?.collectIsPressedAsState()?.value ?: false
    val isPressed = isPointerPressed || isInteractionPressed

    val scale by animateFloatAsState(
        targetValue = if (isPressed) scaleTarget else 1.0f,
        animationSpec = tween(
            durationMillis = 200,
            easing = CubicBezierEasing(0.34f, 1.56f, 0.64f, 1.0f)
        ),
        label = "bouncy_press_scale"
    )

    return this
        .graphicsLayer {
            scaleX = scale
            scaleY = scale
        }
        .pointerInput(Unit) {
            awaitEachGesture {
                awaitFirstDown(requireUnconsumed = false)
                isPointerPressed = true
                waitForUpOrCancellation()
                isPointerPressed = false
            }
        }
}
