package com.budzik.alarm.data

import android.content.Context
import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import com.budzik.alarm.data.local.AlarmDatabase
import com.budzik.alarm.domain.model.AlarmType
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class AlarmDatabaseMigrationTest {

    private val dbName = "migration-test.db"

    /** Exact v3 schema as generated by Room before the `type` column existed. */
    private fun createVersion3Database(context: Context) {
        context.deleteDatabase(dbName)
        val db = SQLiteDatabase.openOrCreateDatabase(context.getDatabasePath(dbName).apply { parentFile?.mkdirs() }, null)
        db.execSQL(
            "CREATE TABLE IF NOT EXISTS `alarms` (`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, `hour` INTEGER NOT NULL, " +
                "`minute` INTEGER NOT NULL, `isEnabled` INTEGER NOT NULL, `daysOfWeekBitmask` INTEGER NOT NULL, " +
                "`difficulty` TEXT NOT NULL, `problemCount` INTEGER NOT NULL, `label` TEXT NOT NULL, " +
                "`wakeUpCheckEnabled` INTEGER NOT NULL, `wakeUpCheckMinutes` INTEGER NOT NULL, `seriesId` TEXT, " +
                "`seriesPosition` INTEGER NOT NULL, `seriesTotal` INTEGER NOT NULL, `nextTriggerAt` INTEGER NOT NULL)"
        )
        db.execSQL(
            "CREATE TABLE IF NOT EXISTS `ringing_state` (`id` INTEGER NOT NULL, `alarmId` INTEGER NOT NULL, " +
                "`isRinging` INTEGER NOT NULL, `difficulty` TEXT NOT NULL, `problemCount` INTEGER NOT NULL, " +
                "`solvedCount` INTEGER NOT NULL, PRIMARY KEY(`id`))"
        )
        fun insert(id: Int, label: String, seriesId: String?) {
            db.execSQL(
                "INSERT INTO alarms VALUES ($id, 7, 0, 1, 0, 'EASY', 1, ?, 0, 5, ?, 0, 0, 0)",
                arrayOf(label, seriesId)
            )
        }
        insert(1, "Alarm", null)
        insert(2, "Seria #1", "abc")
        insert(3, "Drzemka (+20 min)", null)
        insert(4, "Test Seria #1", "xyz")
        db.version = 3
        db.close()
    }

    @Test
    fun migration_3_to_4_keeps_alarms_and_sets_type() = runBlocking {
        val context = ApplicationProvider.getApplicationContext<Context>()
        createVersion3Database(context)

        val room = Room.databaseBuilder(context, AlarmDatabase::class.java, dbName)
            .addMigrations(AlarmDatabase.MIGRATION_3_4)
            .allowMainThreadQueries()
            .build()
        try {
            val types = (1L..4L).associateWith { room.alarmDao().getAlarmById(it)?.type }
            assertEquals(AlarmType.SINGLE.name, types[1L])
            assertEquals(AlarmType.SERIES.name, types[2L])
            assertEquals(AlarmType.NAP.name, types[3L])
            assertEquals(AlarmType.TEST.name, types[4L])
        } finally {
            room.close()
            context.deleteDatabase(dbName)
        }
    }
}
